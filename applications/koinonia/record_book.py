"""Keep the case of a book written by communities as an archive (the design record of 2026-11-26, Section 6), and draw its figures.

    python applications/koinonia/record_book.py <society folder> research/experiments/2026-11-26-koinonia-book/<run>

Writes into the run's folder, then packs it as a BagIt bag by archeion and validates it:

- ``society.json`` (every community's constitution and chronicle, the agents, the book with every body delivered), ``behaviour.jsonl``
  (every participant's behaviour, sealed entry by entry as it ran), ``rounds.jsonl`` (each round's tallies);
- ``journal.jsonl``: the rounds' measures sealed round by round by archeion's rule;
- ``prov.json``: the lineage of the book as W3C PROV-JSON: each series the World Bank's file (entity, with its digest), each result
  generated by an analyst's plan from series and replicated by another, each version written from results by a writer, each review
  of a version by a reviewer, each section's adoption by the partnership's decision; every agent acting on behalf of who lent it;
- ``measures.json``: what the case measures (rounds and money by stage, adoption by regime, revisions, audits, petitions);
- ``figures/*.svg``.
"""

from __future__ import annotations

import datetime as _dt
import json
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "api" / "python"))
sys.path.insert(0, str(Path(__file__).resolve().parent))

import record as rec  # noqa: E402
from koinonia import behaviour  # noqa: E402
from science import archive  # noqa: E402

PAYLOAD = ("society.json", "behaviour.jsonl", "rounds.jsonl", "journal.jsonl", "prov.json", "measures.json")


def prov(society: dict) -> dict:
    ns = "koinonia:"
    b = society["book"]
    doc = {"prefix": {"koinonia": "https://noetarium.example/koinonia#"}, "entity": {}, "activity": {}, "agent": {}, "wasGeneratedBy": {},
           "wasAssociatedWith": {}, "actedOnBehalfOf": {}, "used": {}, "wasDerivedFrom": {}}
    for p in society["parties"].values():
        doc["agent"][ns + p["id"]] = {"prov:type": p["kind"], "prov:label": p.get("label", p["id"])}
    for a in society["agents"].values():
        doc["agent"][ns + a["id"]].update({"koinonia:policy": a["policy"], "koinonia:model": a.get("model", ""), "koinonia:role": a["role"]})
        doc["actedOnBehalfOf"][f"_:b-{a['id']}"] = {"prov:delegate": ns + a["id"], "prov:responsible": ns + a["sponsor"]}
    n = 0

    def rel(kind, **kw):
        nonlocal n
        n += 1
        doc[kind][f"_:{kind[:3]}-{n}"] = kw

    for rid, r in b["results"].items():
        ent, act = f"{ns}result/{rid}", f"{ns}analysis/{rid}"
        doc["entity"][ent] = {"koinonia:tool": r.get("tool"), "koinonia:digest": r.get("digest"), "koinonia:section": r.get("section"), "koinonia:grade": "C"}
        doc["activity"][act] = {"prov:type": "analysis", "koinonia:params": json.dumps(r.get("params"), ensure_ascii=False)}
        rel("wasGeneratedBy", **{"prov:entity": ent, "prov:activity": act})
        rel("wasAssociatedWith", **{"prov:activity": act, "prov:agent": ns + str(r.get("by"))})
        if r.get("replicated_by"):
            rel("wasAssociatedWith", **{"prov:activity": act, "prov:agent": ns + r["replicated_by"], "prov:role": "replicated"})
        for i in r.get("inputs", []):
            s_ent = f"{ns}series/{i['code']}"
            doc["entity"].setdefault(s_ent, {"koinonia:sha256": i.get("sha256"), "koinonia:retrieved": i.get("retrieved"), "prov:label": "World Bank, World Development Indicators"})
            rel("used", **{"prov:activity": act, "prov:entity": s_ent})
    for vid, v in b["versions"].items():
        ent, act = f"{ns}version/{vid}", f"{ns}writing/{vid}"
        doc["entity"][ent] = {"koinonia:section": v["section"], "koinonia:n": v["n"], "koinonia:words": len(v["text"].split()), "koinonia:grade": "C"}
        doc["activity"][act] = {"prov:type": "writing"}
        rel("wasGeneratedBy", **{"prov:entity": ent, "prov:activity": act})
        rel("wasAssociatedWith", **{"prov:activity": act, "prov:agent": ns + v["by"]})
        if v.get("parent"):
            rel("wasDerivedFrom", **{"prov:generatedEntity": ent, "prov:usedEntity": f"{ns}version/{v['parent']}", "prov:type": "prov:Revision"})
        for c in v.get("claims", []):
            rid = str(c.get("fact", "")).split(": ", 1)[0]
            if rid in b["results"]:
                rel("used", **{"prov:activity": act, "prov:entity": f"{ns}result/{rid}"})
    for rid, r in b["reviews"].items():
        act = f"{ns}review/{rid}"
        doc["activity"][act] = {"prov:type": "review", "koinonia:level": r.get("level"), "koinonia:recommend": r.get("recommend"), "koinonia:regime": r.get("regime")}
        rel("used", **{"prov:activity": act, "prov:entity": f"{ns}version/{r['version']}"})
        rel("wasAssociatedWith", **{"prov:activity": act, "prov:agent": ns + r["by"]})
    return doc


def measures(society: dict, rounds: list[dict]) -> dict:
    b = society["book"]
    by_regime: dict[str, dict] = {}
    for vid, v in b["versions"].items():
        rs = [r for r in b["reviews"].values() if r["version"] == vid]
        if not rs:
            continue
        g = by_regime.setdefault(rs[0].get("regime") or "?", {"versions": 0, "adopted": 0, "reviews": 0, "audited": 0, "wrong": 0})
        g["versions"] += 1
        g["reviews"] += len(rs)
        g["adopted"] += int(b["sections"].get(v["section"], {}).get("adopted") == vid or any(a["version"] == vid for a in b["audits"]))
    for a in b["audits"]:
        rs = [r for r in b["reviews"].values() if r["version"] == a["version"]]
        if rs:
            g = by_regime.setdefault(rs[0].get("regime") or "?", {"versions": 0, "adopted": 0, "reviews": 0, "audited": 0, "wrong": 0})
            g["audited"] += a["checked"]
            g["wrong"] += len(a["wrong"])
    versions = [sum(1 for v in b["versions"].values() if v["section"] == sid) for sid in b["sections"]]
    calls_by_role: dict[str, dict] = {}
    for a in society["agents"].values():
        t = calls_by_role.setdefault(a["role"], {"calls": 0, "usd": 0.0, "agents": 0})
        t["calls"] += a["tally"].get("calls", 0)
        t["usd"] = round(t["usd"] + a["tally"].get("usd", 0.0), 4)
        t["agents"] += 1
    return {"rounds": len(rounds), "charter": b["call"].get("charter"), "founded at": b["call"].get("founded at"), "members": b["call"].get("members"),
            "counts": None, "by regime": by_regime, "versions per section": {str(k): versions.count(k) for k in sorted(set(versions))},
            "petitions": {p["name"]: p["status"] for p in b["petitions"].values()}, "tools": list(b["tools"]),
            "calls by role": calls_by_role, "usd": round(sum(t["usd"] for t in calls_by_role.values()), 4), "milestones": b["events"]}


def figures(run: Path, society: dict, rounds: list[dict]) -> list[str]:
    fig = run.parent / "figures" / run.name  # beside the bag, so that the bag holds only its payload and tags
    fig.mkdir(parents=True, exist_ok=True)
    out = []
    stages = ("data", "analysis", "draft", "review", "revision", "adopted")
    series = [{"label": st, "points": [(r["turn"], r.get(st) or 0) for r in rounds], "color": c, "dash": ""}
              for st, c in zip(stages, ("#9C8FA0", "#6F6BA8", "#C2648F", "#D08C3A", "#A2553F", "#5E7F4E"))]
    (fig / "stages.svg").write_text(rec.chart(series, "round", "sections", "Sections by stage, round by round"), encoding="utf-8")
    out.append("stages.svg")
    spent = [{"label": "dollars spent", "points": [(r["turn"], r.get("usd run") or 0) for r in rounds], "color": "#7A3E6B", "dash": ""}]
    (fig / "spending.svg").write_text(rec.chart(spent, "round", "dollars", "What the agents' models cost, round by round"), encoding="utf-8")
    out.append("spending.svg")
    return out


def main(argv: list[str]) -> int:
    src, run = Path(argv[0]), Path(argv[1])
    run.mkdir(parents=True, exist_ok=True)
    for name in ("society.json", "behaviour.jsonl", "rounds.jsonl"):
        if (src / name).is_file():
            shutil.copyfile(src / name, run / name)
    society = json.loads((run / "society.json").read_text(encoding="utf-8"))
    rounds = [json.loads(x) for x in (run / "rounds.jsonl").read_text(encoding="utf-8").splitlines() if x.strip()]
    entries, head = [], archive.GENESIS
    for r in rounds:
        sealed = archive.sealed(head, when=f"{r['turn']:06d}", who="the work", what="round", about=str(r["turn"]), note=behaviour.digest(r))
        entries.append(sealed)
        head = sealed["seal"]
    (run / "journal.jsonl").write_text("".join(json.dumps(e) + "\n" for e in entries), encoding="utf-8")
    (run / "prov.json").write_text(json.dumps(prov(society), ensure_ascii=False, indent=1), encoding="utf-8")
    m = measures(society, rounds)
    (run / "measures.json").write_text(json.dumps(m, ensure_ascii=False, indent=1), encoding="utf-8")
    figs = figures(run, society, rounds)
    j = behaviour.verify(behaviour.entries_of(run / "behaviour.jsonl"), society["journal"]["head"], society["journal"]["entries"])
    rec.PAYLOAD = PAYLOAD
    bag = rec.pack(run, society)
    print(json.dumps({"run": str(run), "figures": figs, "behaviour journal holds": j["holds"], "bag": bag.get("valid", bag)}, indent=1))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))

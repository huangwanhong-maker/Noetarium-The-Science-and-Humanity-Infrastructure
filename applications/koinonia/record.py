"""Keep Koinonia's case studies as archives, and draw their figures (ADR 0169).

    python applications/koinonia/record.py research/experiments/2026-11-26-koinonia-cases

For each run kept by ``run_case.py --record`` (a folder holding ``rounds.jsonl``, ``society.json`` and ``summary.json``):

- ``journal.jsonl``: the trajectory sealed round by round by archeion's rule (each entry's seal the SHA-256 of the one before and its
  fields), its note the digest of the round's row; verified by archeion through the API's archive composition;
- ``prov.json``: the lineage of every finding as W3C PROV-JSON: each finding an entity generated by the deliveries of checks (each an
  activity associated with the agent that delivered it), each agent acting on behalf of the party that lent it, each adjudication
  an activity of the guild's aide;
- the run packed as a BagIt bag by archeion (payload under ``data/``, its manifests in SHA-256 and SHA-512), and validated.

Each community's own record was sealed act by act by thesmos's chronicle as it ran (the heads in ``summary.json``), and replays
against those seals. The figures are written to ``figures/`` beside the runs, as SVG.
"""

from __future__ import annotations

import datetime as _dt
import hashlib
import json
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "api" / "python"))

from science import archive  # noqa: E402

PAYLOAD = ("rounds.jsonl", "society.json", "summary.json", "journal.jsonl", "prov.json")


def runs(folder: Path) -> list[Path]:
    return sorted(p.parent if p.parent.name != "data" else p.parent.parent for p in folder.glob("*/**/society.json"))


def data_of(run: Path) -> Path:
    return run / "data" if (run / "data" / "society.json").is_file() else run


def journal(run: Path) -> list[dict]:
    rows = (data_of(run) / "rounds.jsonl").read_text(encoding="utf-8").splitlines()
    out, previous = [], archive.GENESIS
    for row in rows:
        r = json.loads(row)
        e = archive.sealed(previous, when=f"{r['turn']:06d}", who="koinonia", what="round", about=run.name, note=hashlib.sha256(row.encode("utf-8")).hexdigest())
        out.append(e)
        previous = e["seal"]
    return out


def prov(society: dict) -> dict:
    """W3C PROV-JSON of the findings: entities, activities, agents and the relations between them."""
    ns = "koinonia:"
    doc = {"prefix": {"koinonia": "https://noetarium.example/koinonia#"}, "entity": {}, "activity": {}, "agent": {},
           "wasGeneratedBy": {}, "wasAssociatedWith": {}, "actedOnBehalfOf": {}, "used": {}}
    for p in society["parties"].values():
        doc["agent"][ns + p["id"]] = {"prov:type": p["kind"], "prov:label": p.get("label", p["id"])}
    for a in society["agents"].values():
        doc["agent"][ns + a["id"]].update({"koinonia:policy": a["policy"], "koinonia:model": a.get("model", ""), "koinonia:role": a["role"]})
        doc["actedOnBehalfOf"][f"_:b-{a['id']}"] = {"prov:delegate": ns + a["id"], "prov:responsible": ns + a["sponsor"]}
    n = 0
    for cid, body in society["work"]["bodies"].items():
        act = ns + "delivery/" + cid
        doc["activity"][act] = {"prov:type": body.get("kind", ""), "koinonia:provider": body.get("provider", "")}
        doc["wasAssociatedWith"][f"_:w-{cid}"] = {"prov:activity": act, "prov:agent": ns + body["by"]}
        for f in body.get("findings", []) or ([{"entry": cid.split("~")[0], **body["adjudication"]}] if body.get("adjudication") else []):
            n += 1
            ent = f"{ns}verdict/{n}"
            doc["entity"][ent] = {"koinonia:entry": f["entry"], "koinonia:verdict": f["verdict"], "koinonia:why": f.get("why", ""), "koinonia:grade": "C"}
            doc["wasGeneratedBy"][f"_:g-{n}"] = {"prov:entity": ent, "prov:activity": act}
    for e, f in society["work"]["findings"].items():
        ent = f"{ns}finding/{e}"
        doc["entity"][ent] = {"koinonia:entry": e, "koinonia:finding": f["finding"], "koinonia:how": f["how"], "koinonia:grade": "C"}
    return doc


def pack(run: Path, society: dict) -> dict:
    """Moves the payload under data/, asks archeion for the bag's tag files and writes them; then validates the bag."""
    data = run / "data"
    data.mkdir(exist_ok=True)
    for name in PAYLOAD:
        if (run / name).is_file():
            shutil.move(str(run / name), str(data / name))
    payload = {name: archive.path(data / name) for name in PAYLOAD if (data / name).is_file()}  # paths within data/, which archeion adds
    info = [["Source-Organization", "Koinonia, a work of Noetarium (invented society)"], ["External-Description", society.get("description", "")[:400]],
            ["Bag-Group-Identifier", run.parent.name], ["External-Identifier", run.name]]
    bag = archive.ask("package", payload=payload, info=info, date=_dt.date.today().isoformat())
    for path, text in bag["tags"].items():
        (run / path).write_text(text, encoding="utf-8", newline="\n")
    files = {p.relative_to(run).as_posix(): archive.path(p) for p in run.rglob("*") if p.is_file()}
    return archive.ask("validate", files=files)


# ---- figures ----------------------------------------------------------------------------------------------------------------------
INK, MUTED, HAIR, PAPER = "#3A2E3D", "#75697A", "#E2D8DD", "#FAF6F2"
ARR = {"gift": ("#5F8058", ""), "credit": ("#A94C44", "6 4"), "transferable credit": ("#A87A2E", "2 3"),
       "cleared credit": ("#6E5FAA", "8 3 2 3"), "provision": ("#3F6E8C", "12 4")}


def chart(series: list[dict], xlabel: str, ylabel: str, title: str, width=760, height=380, bands=None, marks=None) -> str:
    left, right, top, bottom = 64, 150, 34, 50
    xs = [x for s in series for x, _ in s["points"]] or [0, 1]
    ys = [y for s in series for _, y in s["points"]] or [0, 1]
    x0, x1, y1 = 0, max(xs) or 1, max(1, max(ys))
    X = lambda x: left + (width - left - right) * (x - x0) / (x1 - x0)  # noqa: E731
    Y = lambda y: height - bottom - (height - top - bottom) * y / y1  # noqa: E731
    out = [f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {width} {height}" font-family="Source Serif 4, Georgia, serif" font-size="12">',
           f'<rect width="{width}" height="{height}" fill="{PAPER}"/>', f'<text x="{left}" y="20" fill="{INK}" font-size="14">{title}</text>']
    for b in bands or []:
        out.append(f'<rect x="{X(b["from"]):.1f}" y="{top}" width="{X(b["to"]) - X(b["from"]):.1f}" height="{height - top - bottom}" fill="{b["color"]}" opacity="0.10"/>')
        out.append(f'<text x="{X(b["from"]) + 4:.1f}" y="{top + 13}" fill="{b["color"]}" font-size="11">{b["label"]}</text>')
    step = max(1, round(y1 / 5))
    for v in range(0, int(y1) + 1, step):
        out.append(f'<line x1="{left}" x2="{width - right}" y1="{Y(v):.1f}" y2="{Y(v):.1f}" stroke="{HAIR}"/><text x="{left - 8}" y="{Y(v) + 4:.1f}" text-anchor="end" fill="{MUTED}">{v}</text>')
    xstep = max(1, round(x1 / 8))
    for v in range(0, int(x1) + 1, xstep):
        out.append(f'<text x="{X(v):.1f}" y="{height - bottom + 16}" text-anchor="middle" fill="{MUTED}">{v}</text>')
    out.append(f'<line x1="{left}" x2="{width - right}" y1="{height - bottom}" y2="{height - bottom}" stroke="{MUTED}"/>')
    out.append(f'<text x="{(left + width - right) / 2}" y="{height - 12}" text-anchor="middle" fill="{INK}">{xlabel}</text>')
    out.append(f'<text transform="translate(16,{(top + height - bottom) / 2}) rotate(-90)" text-anchor="middle" fill="{INK}">{ylabel}</text>')
    placed = []
    for s in series:
        if not s["points"]:
            continue
        d = " ".join(f'{"M" if i == 0 else "L"}{X(x):.1f} {Y(y):.1f}' for i, (x, y) in enumerate(s["points"]))
        dash = f' stroke-dasharray="{s["dash"]}"' if s.get("dash") else ""
        out.append(f'<path d="{d}" fill="none" stroke="{s["color"]}" stroke-width="1.8"{dash}/>')
        lx, ly = s["points"][-1]
        y = Y(ly)
        while any(abs(y - p) < 13 for p in placed):
            y += 13
        placed.append(y)
        out.append(f'<text x="{X(lx) + 6:.1f}" y="{y + 4:.1f}" fill="{s["color"]}">{s["label"]}</text>')
    for m in marks or []:
        out.append(f'<text x="{X(m["x"]):.1f}" y="{Y(m["y"]) - 6:.1f}" text-anchor="middle" fill="{m["color"]}" font-size="13">{m["glyph"]}</text>')
    out.append("</svg>")
    return "\n".join(out)


def outstanding(society: dict, rounds: int) -> list[tuple[int, int]]:
    league = next((c for c in society["communities"] if c["preset"] in ("first-league", "league")), None)
    if league is None:
        return []
    delta = [0] * (rounds + 2)
    for a in league["record"]:
        f = a["fields"]
        if a["kind"] == "commit" and f.get("matter") == "service":
            delta[a["turn"]] += 1
        elif a["kind"] in ("accept", "release") and f.get("id", "").startswith("s-"):
            delta[a["turn"]] -= 1
    out, level = [], 0
    for t in range(rounds + 1):
        level += delta[t]
        out.append((t, level))
    return out


def arrangements(society: dict, rounds: int) -> list[dict]:
    league = next((c for c in society["communities"] if c["preset"] in ("first-league", "league")), None)
    spans, current, since = [], society["work"].get("regime") or "gift", 0
    texts = {a["fields"].get("id"): a["fields"].get("change.compact", "") for a in (league or {}).get("record", []) if a["kind"] == "propose"}
    for a in (league or {}).get("record", []):
        if a["kind"] == "amend":
            word = texts.get(a["fields"].get("id"), "")[len("circulation: "):].split(" (")[0]
            spans.append({"from": since, "to": a["turn"], "label": current, "color": ARR.get(current, (MUTED, ""))[0]})
            current, since = word, a["turn"]
    spans.append({"from": since, "to": rounds, "label": current, "color": ARR.get(current, (MUTED, ""))[0]})
    return spans


def figures(folder: Path) -> list[str]:
    out = folder / "figures"
    out.mkdir(exist_ok=True)
    made = []
    loaded = {}
    for run in runs(folder):
        d = data_of(run)
        loaded[run.name] = (json.loads((d / "society.json").read_text(encoding="utf-8")), [json.loads(x) for x in (d / "rounds.jsonl").read_text(encoding="utf-8").splitlines()])
    tri = {k: v for k, v in loaded.items() if k.startswith("three-60-") and k.endswith("-stand-in")}
    if tri:
        work, debts = [], []
        for name, (soc, rows) in sorted(tri.items()):
            word = name[len("three-60-"):-len("-stand-in")].replace("-", " ")
            color, dash = ARR.get(word, (MUTED, ""))
            work.append({"label": word, "color": color, "dash": dash, "points": [(r["turn"], r["work"]["holds"] + r["work"]["fault"]) for r in rows]})
            debts.append({"label": word, "color": color, "dash": dash, "points": outstanding(soc, len(rows))})
        (out / "triangle-entries-settled.svg").write_text(chart(work, "Round", "Entries settled", "Entries settled under five arrangements of circulation"), encoding="utf-8")
        (out / "triangle-debts-outstanding.svg").write_text(chart(debts, "Round", "Debts outstanding", "Debts outstanding between communities under five arrangements"), encoding="utf-8")
        made += ["triangle-entries-settled.svg", "triangle-debts-outstanding.svg"]
    for name, (soc, rows) in loaded.items():
        if not name.startswith("three-envoys-"):
            continue
        n = len(rows)
        league = next(c for c in soc["communities"] if c["preset"] == "first-league")
        marks = [{"x": a["turn"], "y": 0.3, "glyph": "◆", "color": ARR["transferable credit"][0]} for a in league["record"] if a["kind"] == "assign"]
        marks += [{"x": a["turn"], "y": 0.3, "glyph": "○", "color": ARR["cleared credit"][0]} for a in league["record"] if a["kind"] == "release" and a["fields"].get("why") == "cleared"]
        series = [{"label": "debts outstanding", "color": INK, "points": outstanding(soc, n)},
                  {"label": "entries settled ÷ 10", "color": MUTED, "dash": "2 3", "points": [(r["turn"], (r["work"]["holds"] + r["work"]["fault"]) / 10) for r in rows]}]
        (out / f"{name}.svg").write_text(chart(series, "Round", "Count", "The league's arrangement in force, its debts, claims passed on (◆) and cycles cleared (○)",
                                               bands=arrangements(soc, n), marks=marks), encoding="utf-8")
        made.append(f"{name}.svg")
    for name, (soc, rows) in loaded.items():
        if not name.startswith("two-"):
            continue
        series = [{"label": "holds", "color": ARR["gift"][0], "points": [(r["turn"], r["work"]["holds"]) for r in rows]},
                  {"label": "at fault", "color": ARR["credit"][0], "dash": "6 4", "points": [(r["turn"], r["work"]["fault"]) for r in rows]},
                  {"label": "adjudicated", "color": ARR["cleared credit"][0], "dash": "2 3", "points": [(r["turn"], r["work"]["adjudicated"]) for r in rows]},
                  {"label": "cents spent", "color": ARR["transferable credit"][0], "dash": "8 3 2 3", "points": [(r["turn"], r["usd"] * 100) for r in rows]}]
        (out / f"{name}.svg").write_text(chart(series, "Round", "Count", "Findings of the commons and the guild, and what the models cost"), encoding="utf-8")
        made.append(f"{name}.svg")
    return made


def main(argv: list[str]) -> int:
    folder = Path(argv[0]) if argv else ROOT / "research" / "experiments" / "2026-11-26-koinonia-cases"
    print("figures:", figures(folder))
    for run in runs(folder):
        d = data_of(run)
        society = json.loads((d / "society.json").read_text(encoding="utf-8"))
        entries = journal(run)
        (d / "journal.jsonl").write_text("".join(json.dumps(e, ensure_ascii=False) + "\n" for e in entries), encoding="utf-8")
        (d / "prov.json").write_text(json.dumps(prov(society), ensure_ascii=False, indent=1), encoding="utf-8")
        verified = archive.ask("journal", entries=entries, head=entries[-1]["seal"] if entries else "")
        bag = pack(run, society)
        print(f"{run.name}: journal of {len(entries)} rounds {verified['verdict'].get('status', verified['verdict'])}; bag valid {bag['valid']} complete {bag['complete']}"
              + (f" faults {bag['faults']}" if bag["faults"] else ""))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
